<p><strong>Zakres danych.</strong> Imię i nazwisko lub nazwa firmy, adres do faktury, NIP (jeśli dotyczy), adres e-mail do wysyłki faktury, dane płatności (kwota, data, rachunek, z którego wpłynęła płatność, tytuł przelewu).</p>
